HINT_VARIANTS = ("hint_short", "hint_medium", "hint_detailed")
PI_MODES = ("none", "answer", "rollout", "full", *HINT_VARIANTS, "hint")
DEFAULT_PI_MODES = ("none", "answer", "rollout", "full", *HINT_VARIANTS)


class RolloutAttempt(NamedTuple):
    question: str
    completion: str
    correct: bool


def build_teacher_messages(problem: dict, pi_mode: str) -> list[dict]:
    """Teacher prompt for one PI mode, mirroring SDFTTrainer._compose_teacher_prompt:
    keep the system turn, fold the privileged context into the user turn via
    TEACHER_PROMPT_TEMPLATE. `none` is the plain student prompt (no PI)."""
    q = problem["question"]
    messages = format_prompt(
        q, problem.get("dataset", "deepmath")
    )  # [system, user(question)]
    if pi_mode == "none":
        return messages
    if pi_mode == "full":
        privileged_context = PI_FULL.format(demo=problem["solution"])
    elif pi_mode == "answer":
        privileged_context = answer_context(
            problem["answer"], problem.get("dataset", "deepmath")
        )
    elif pi_mode == "hint" or pi_mode in HINT_VARIANTS:
        privileged_context = PI_HINT.format(hint=problem[pi_mode])
    elif pi_mode == "rollout":
        privileged_context = PI_ROLLOUT.format(attempt=problem["rollout"])
    else:
        raise ValueError(f"unknown pi_mode {pi_mode!r}")
    user_text = TEACHER_PROMPT_TEMPLATE.format(
        prompt=q, privileged_context=privileged_context
    )
    return messages[:-1] + [{"role": "user", "content": user_text}]


def load_eval_problems(
    model: str,
    num_problems: int,
    seed: int,
    need_full: bool,
    dataset: str = "deepmath",
    required_question_indices: set[int] | None = None,
) -> list[dict]:
    """Random subset of the hint cache, with `full` solutions rejoined from `dataset`.

    The hint cache defines the set (every problem has a hint) and carries
    question/final_answer/hint; we assert it was generated by `model` on `dataset`
    (self-purity).
    """
    path = hint_path(model, dataset)
    if not os.path.isdir(path):
        raise FileNotFoundError(
            f"No hint cache for {model} on {dataset} at {path}. Generate it first:\n"
            f"  python -m utils.gen_hints --model {model} --dataset {dataset} --max-samples <N>"
        )
    hints = load_from_disk(path)
    gen_models = set(hints.unique("gen_model"))
    if gen_models != {model}:
        raise ValueError(
            f"Hint cache at {path} was generated by {gen_models}, not {model!r}."
        )
    if "dataset" in hints.column_names and set(hints.unique("dataset")) != {dataset}:
        raise ValueError(
            f"Hint cache at {path} was generated for dataset "
            f"{set(hints.unique('dataset'))}, not {dataset!r}."
        )

    eligible_idx = list(range(len(hints)))
    if required_question_indices is not None:
        eligible_idx = [idx for idx in eligible_idx if idx in required_question_indices]
        if not eligible_idx:
            raise ValueError(
                "The hint and rollout-PI caches have no source indices in common."
            )
        if len(eligible_idx) < num_problems:
            print(
                f"  warning: rollout-PI cache covers only {len(eligible_idx)} eligible "
                f"hint questions; requested {num_problems}"
            )

    n = min(num_problems, len(eligible_idx))
    idx = sorted(random.Random(seed).sample(eligible_idx, n))
    sub = hints.select(idx)

    problems = [
        {
            "question_idx": question_idx,
            "dataset": dataset,
            "question": row["question"],
            "answer": str(row["final_answer"]),
            "hint": row["hint"],
        }
        for question_idx, row in zip(idx, sub, strict=True)
    ]

    if need_full:
        # Rejoin worked solutions by question (hints came from these dataset rows).
        sol_by_q = {
            r["question"]: r["solution"] for r in DATASET_REGISTRY_TRAIN[dataset]()
        }
        for p in problems:
            p["solution"] = sol_by_q.get(p["question"])
        missing = sum(p["solution"] is None for p in problems)
        if missing:
            print(
                f"  warning: {missing}/{len(problems)} problems had no {dataset} solution to rejoin"
            )
    return problems


def load_demo_problems(cohort_dir, model, pi_modes, num_problems, hint_sample_idx=0):
    """Reuse fixed PI artifacts; validity selection never observes generated answers."""
    manifest, cohort = load_cohort(cohort_dir)
    if manifest["model"] != model or manifest["model_identity"] != model_identity(
        model
    ):
        raise ValueError("Self-teacher must match the prepared cohort model")
    modes = [mode for mode in pi_modes if mode in HINT_VARIANTS]
    variants, hint_meta = {}, None
    if modes:
        hints_dir = Path(cohort_dir) / "hints"
        if not all(
            (hints_dir / name).is_file() for name in ("manifest.json", "hints.jsonl")
        ):
            raise FileNotFoundError(
                f"Hint artifacts are incomplete at {hints_dir}; finish "
                "python -m utils.gen_hint_variants for this cohort before evaluating"
            )
        variants, hint_meta = load_variants(hints_dir, cohort)
        config = hint_meta["config"]
        if (
            config["model"] != model
            or config["model_identity"] != manifest["model_identity"]
            or config["revision"] != manifest["revision"]
        ):
            raise ValueError(
                "Hint generator must match the self-teacher model and revision"
            )
        if not 0 <= hint_sample_idx < config["samples_per_level"]:
            raise ValueError("Hint sample index is outside the generated sample range")
    problems, excluded = [], Counter()
    for row in cohort:
        problem = dict(row, answer=row["final_answer"], dataset="deepmath")
        invalid = []
        for mode in modes:
            matches = [
                h
                for h in variants.get((row["question_id"], mode), [])
                if h["sample_idx"] == hint_sample_idx
            ]
            if len(matches) != 1:
                raise ValueError(
                    f"Missing fixed {mode} sample for {row['question_id']}"
                )
            hint = matches[0]
            if hint["invalid_reason"] or hint["truncated"]:
                invalid.append(mode)
            problem[mode] = hint["hint"]
        if invalid:
            excluded[f"invalid_or_truncated_{invalid[0]}"] += 1
            continue
        if "rollout" in pi_modes and not problem.get("rollout"):
            excluded["missing_rollout"] += 1
            continue
        # Scoring token IDs are irrelevant: accuracy uses fresh free-running responses.
        for key in ("prompt_ids", "target_ids"):
            problem.pop(key, None)
        problems.append(problem)
    n_valid = len(problems)
    if num_problems:
        problems = problems[:num_problems]
    return problems, {
        "cohort_dir": str(Path(cohort_dir).resolve()),
        "cohort_hash": manifest["cohort_hash"],
        "revision": manifest["revision"],
        "tokenizer_hash": manifest["tokenizer_hash"],
        "n_prepared": len(cohort),
        "n_valid_pi": n_valid,
        "exclusions": dict(excluded),
        "hint_sample_idx": hint_sample_idx,
        "hint_selection": "fixed_sample_idx_without_teacher_outcomes",
        "hints_hash": hint_meta["hints_hash"] if hint_meta else None,
        "rollout_pi_root": manifest["rollout_pi_root"],
        "rollout_pi_sample_idx": manifest["rollout_pi_sample_idx"],
    }


def paired_against_none(results_by_mode, ks, bootstrap_samples, seed):
    """Paired question-level differences, including CIs for each arm's accuracy."""
    import numpy as np

    baseline = results_by_mode["none"]
    ids = [r["question_idx"] for r in baseline]
    if not ids or len(set(ids)) != len(ids):
        raise ValueError("Baseline question IDs must be nonempty and unique")
    draws = np.random.default_rng(seed).integers(
        len(ids), size=(bootstrap_samples, len(ids))
    )
    report = {}
    for mode, results in results_by_mode.items():
        indexed = {r["question_idx"]: r for r in results}
        if len(indexed) != len(results) or set(indexed) != set(ids):
            raise ValueError(f"Cannot pair {mode}: question IDs differ")
        metrics = {}
        for k in ks:

            def values(rows, k=k):
                if any(
                    not 0 <= r["n_correct"] <= r["n_samples"] or r["n_samples"] < k
                    for r in rows
                ):
                    raise ValueError("Invalid sample counts for pass@k")
                return np.array(
                    [pass_at_k(r["n_samples"], r["n_correct"], k) for r in rows]
                )

            arm = values([indexed[qid] for qid in ids])
            delta = arm - values(baseline)
            metrics[f"pass@{k}"] = {
                "mean": float(arm.mean()),
                "ci95": np.quantile(arm[draws].mean(axis=1), [0.025, 0.975]).tolist(),
                "delta_vs_none": float(delta.mean()),
                "delta_ci95": np.quantile(
                    delta[draws].mean(axis=1), [0.025, 0.975]
                ).tolist(),
            }
        report[mode] = metrics
    return report


def load_rollout_pi(
    model: str,
    dataset: str,
    root: str,
    sample_idx: int,
) -> tuple[dict[int, RolloutAttempt], dict]:
    """Load one fixed attempt per source index; reward never affects which attempt is kept."""
    path = rollout_path(model, dataset, root)
    if not os.path.isdir(path):
        raise FileNotFoundError(
            f"No rollout-PI cache for {model} on {dataset} at {path}. Generate it first:\n"
            "  python -m utils.gen_rollouts "
            f"--model {model} --dataset {dataset} --output-root {root} "
            "--skip-logp-scoring"
        )
    cache = load_from_disk(path)
    required = {
        "question",
        "question_idx",
        "completion_text",
        "reward",
        "sample_idx",
        "gen_model",
        "dataset",
        "question_source",
        "mixed_only",
        "generation_seed",
        "max_completion_length",
    }
    missing = required.difference(cache.column_names)
    if missing:
        raise ValueError(
            f"Rollout-PI cache at {path} is missing provenance columns {sorted(missing)}. "
            "Regenerate it with the current gen_rollouts.py and --force."
        )
    if set(cache.unique("gen_model")) != {model}:
        raise ValueError(
            f"Rollout-PI cache at {path} was generated by "
            f"{set(cache.unique('gen_model'))}, not {model!r}."
        )
    if set(cache.unique("dataset")) != {dataset}:
        raise ValueError(
            f"Rollout-PI cache at {path} was generated for "
            f"{set(cache.unique('dataset'))}, not {dataset!r}."
        )
    if set(cache.unique("question_source")) != {"hints"}:
        raise ValueError(
            f"Rollout-PI cache at {path} was not generated from the hint cache."
        )
    if set(cache.unique("mixed_only")) != {False}:
        raise ValueError(
            "The rollout-PI cache was generated with --mixed-only. That selection uses "
            "verifier outcomes and invalidates the unverified-rollout ablation."
        )

    attempts: dict[int, RolloutAttempt] = {}
    # Select solely on sample_idx. Reward is read only after that choice, as the label for the
    # post-hoc paired analysis; it never affects cache membership or prompt construction.
    for question_idx, question, completion, reward, cached_sample_idx in zip(
        cache["question_idx"],
        cache["question"],
        cache["completion_text"],
        cache["reward"],
        cache["sample_idx"],
        strict=True,
    ):
        if int(cached_sample_idx) != sample_idx:
            continue
        question_idx = int(question_idx)
        if question_idx in attempts:
            raise ValueError(
                f"Rollout-PI cache has duplicate sample_idx={sample_idx} for "
                f"question_idx={question_idx}."
            )
        reward = float(reward)
        if reward not in (0.0, 1.0):
            raise ValueError(
                f"Rollout-PI cache has non-binary reward={reward} for "
                f"question_idx={question_idx}, sample_idx={sample_idx}."
            )
        attempts[question_idx] = RolloutAttempt(question, completion, bool(reward))
    if not attempts:
        available = sorted(int(value) for value in cache.unique("sample_idx"))
        raise ValueError(
            f"No rollout with sample_idx={sample_idx} in {path}; available indices: {available}."
        )

    generation_seeds = sorted(int(value) for value in cache.unique("generation_seed"))
    completion_budgets = sorted(
        int(value) for value in cache.unique("max_completion_length")
    )
    metadata = {
        "cache_path": path,
        "sample_idx": sample_idx,
        "selection_policy": "fixed_sample_idx_without_reward",
        "reward_usage": "posthoc_attempt_correctness_stratification_only",
        "n_available_questions": len(attempts),
        "generation_seeds": generation_seeds,
        "max_completion_lengths": completion_budgets,
    }
    return attempts, metadata


def attach_rollout_pi(
    problems: list[dict], attempts: dict[int, RolloutAttempt]
) -> list[dict]:
    """Attach attempts by source index and verify the two caches still align by text."""
    for problem in problems:
        attempt = attempts[problem["question_idx"]]
        if attempt.question != problem["question"]:
            raise ValueError(
                "Rollout-PI and hint caches disagree at question_idx="
                f"{problem['question_idx']}: rollout has {attempt.question!r}, hint cache "
                f"has {problem['question']!r}."
            )
        problem["rollout"] = attempt.completion
        problem["attempt_correct"] = attempt.correct
    return problems


def _percentile(sorted_values: list[float], quantile: float) -> float:
    """Linearly interpolated percentile for an already sorted, non-empty list."""
    position = (len(sorted_values) - 1) * quantile
    lower = int(position)
    upper = min(lower + 1, len(sorted_values) - 1)
    weight = position - lower
    return sorted_values[lower] * (1 - weight) + sorted_values[upper] * weight


def paired_bootstrap_ci(
    deltas: list[float], num_samples: int, seed: int
) -> list[float]:
    """Problem-level paired bootstrap percentile interval for the mean delta."""
    if not deltas:
        raise ValueError("Cannot bootstrap an empty paired-delta group.")
    if num_samples < 1:
        raise ValueError(f"num_samples must be >= 1, got {num_samples}.")
    rng = random.Random(seed)
    n = len(deltas)
    bootstrap_means = sorted(
        sum(deltas[rng.randrange(n)] for _ in range(n)) / n for _ in range(num_samples)
    )
    return [
        _percentile(bootstrap_means, 0.025),
        _percentile(bootstrap_means, 0.975),
    ]


def paired_rollout_minus_none(
    problems: list[dict],
    results_by_mode: dict[str, list[dict]],
    ks: list[int],
    bootstrap_samples: int,
    seed: int,
) -> tuple[dict, list[dict]]:
    """Paired per-problem rollout-minus-none estimates, stratified by attempt outcome."""
    if not {"none", "rollout"}.issubset(results_by_mode):
        raise ValueError("Paired analysis requires both 'none' and 'rollout' results.")

    indexed: dict[str, dict[int, dict]] = {}
    for mode in ("none", "rollout"):
        by_question: dict[int, dict] = {}
        for result in results_by_mode[mode]:
            question_idx = int(result["question_idx"])
            if question_idx in by_question:
                raise ValueError(
                    f"Duplicate {mode} result for question_idx={question_idx}."
                )
            by_question[question_idx] = result
        indexed[mode] = by_question

    problem_indices = [int(problem["question_idx"]) for problem in problems]
    expected = set(problem_indices)
    for mode in ("none", "rollout"):
        actual = set(indexed[mode])
        if actual != expected:
            raise ValueError(
                f"Cannot pair {mode} results: missing={sorted(expected - actual)}, "
                f"extra={sorted(actual - expected)}."
            )

    per_problem = []
    for problem in problems:
        question_idx = int(problem["question_idx"])
        none = indexed["none"][question_idx]
        rollout = indexed["rollout"][question_idx]
        pass_values = {}
        for k in ks:
            none_value = pass_at_k(none["n_samples"], none["n_correct"], k)
            rollout_value = pass_at_k(rollout["n_samples"], rollout["n_correct"], k)
            pass_values[f"pass@{k}"] = {
                "none": none_value,
                "rollout": rollout_value,
                "delta": rollout_value - none_value,
            }
        per_problem.append(
            {
                "question_idx": question_idx,
                "attempt_correct": bool(problem["attempt_correct"]),
                "none_n_samples": none["n_samples"],
                "none_n_correct": none["n_correct"],
                "rollout_n_samples": rollout["n_samples"],
                "rollout_n_correct": rollout["n_correct"],
                "pass_at_k": pass_values,
            }
        )

    paired = {
        "comparison": "rollout - none",
        "bootstrap_samples": bootstrap_samples,
        "bootstrap_seed": seed,
    }
    for group_index, (label, attempt_correct) in enumerate(
        (("attempt_correct", True), ("attempt_incorrect", False))
    ):
        rows = [row for row in per_problem if row["attempt_correct"] is attempt_correct]
        if not rows:
            raise ValueError(f"Paired analysis group {label!r} has no problems.")
        metrics = {}
        for k in ks:
            key = f"pass@{k}"
            none_values = [row["pass_at_k"][key]["none"] for row in rows]
            rollout_values = [row["pass_at_k"][key]["rollout"] for row in rows]
            deltas = [row["pass_at_k"][key]["delta"] for row in rows]
            metrics[key] = {
                "none": sum(none_values) / len(rows),
                "rollout": sum(rollout_values) / len(rows),
                "delta": sum(deltas) / len(rows),
                "delta_ci95": paired_bootstrap_ci(
                    deltas,
                    bootstrap_samples,
                    seed + group_index * 10_000 + k,
                ),
            }
        paired[label] = {"n_problems": len(rows), "pass_at_k": metrics}
    return paired, per_problem


def restrict_to_pi_feasible(
    problems, tokenizer, budget: int, pi_modes: list[str], enable_thinking=True
):
    """Keep the common subset whose prompt fits under every requested PI condition."""
    feasible = []
    modes = list(dict.fromkeys(pi_modes))
    for problem in problems:
        if "full" in modes and not problem.get("solution"):
            continue
        if "rollout" in modes and "rollout" not in problem:
            continue
        fits = True
        for mode in modes:
            ids = tokenizer.apply_chat_template(
                [build_teacher_messages(problem, mode)],
                add_generation_prompt=True,
                tokenize=True,
                return_dict=True,
                enable_thinking=enable_thinking,
            )["input_ids"][0]
            if len(ids) > budget:
                fits = False
                break
        if fits:
            feasible.append(problem)
    dropped = len(problems) - len(feasible)
    print(
        f"  common eval set = {len(feasible)} problems whose {modes} PI prompts fit "
        f"{budget} tokens (dropped {dropped})"
    )
    return feasible


def restrict_to_full_feasible(problems, tokenizer, budget: int):
    """Keep only problems whose full-PI teacher prompt fits `budget` tokens, so
    every arm is scored on an identical problem set (full is the longest prompt)."""
    feasible = []
    for p in problems:
        if not p.get("solution"):
            continue
        ids = tokenizer.apply_chat_template(
            [build_teacher_messages(p, "full")],
            add_generation_prompt=True,
            tokenize=True,
            return_dict=True,
        )["input_ids"][0]
        if len(ids) <= budget:
            feasible.append(p)
    dropped = len(problems) - len(feasible)
    print(
        f"  common eval set = {len(feasible)} problems whose full-PI prompt fits "
        f"{budget} tokens (dropped {dropped})"
    )
    return feasible


def eval_pi_mode(
    llm,
    tokenizer,
    problems,
    pi_mode,
    sampling_params,
    *,
    enable_thinking=True,
    cache=None,
    batch_size=16,
):
    """Generate and grade in resumable batches, retaining response text for analysis."""
    results = []
    for start in range(0, len(problems), batch_size):
        batch = problems[start : start + batch_size]
        pending, entries = [], []
        for problem in batch:
            prompt = tokenizer.apply_chat_template(
                build_teacher_messages(problem, pi_mode),
                tokenize=False,
                add_generation_prompt=True,
                enable_thinking=enable_thinking,
            )
            key = (
                cache.key(
                    {
                        "prompt": prompt,
                        "answer": problem["answer"],
                        "dataset": problem.get("dataset", "deepmath"),
                    }
                )
                if cache
                else None
            )
            saved = cache.load(key) if cache else None
            entries.append([problem, saved])
            if saved is None:
                pending.append((len(entries) - 1, key, prompt))
        if pending:
            outputs = llm.generate([item[2] for item in pending], sampling_params)
            for (index, key, _), output in zip(pending, outputs, strict=True):
                problem = entries[index][0]
                if len(output.outputs) != sampling_params.n:
                    raise ValueError("Generator returned an unexpected sample count")
                samples = []
                for completion in output.outputs:
                    correct = bool(
                        grade(
                            completion.text,
                            problem["answer"],
                            problem.get("dataset", "deepmath"),
                        )[1]
                    )
                    samples.append(
                        {
                            "text": completion.text,
                            "correct": correct,
                            "finish_reason": completion.finish_reason,
                            "n_tokens": len(completion.token_ids),
                        }
                    )
                saved = {
                    "n_samples": len(samples),
                    "n_correct": sum(s["correct"] for s in samples),
                    "n_truncated": sum(s["finish_reason"] == "length" for s in samples),
                    "samples": samples,
                }
                if cache:
                    cache.save(key, saved)
                entries[index][1] = saved
        for problem, saved in entries:
            results.append(
                dict(
                    saved,
                    question_idx=problem["question_idx"],
                    question_id=problem.get("question_id"),
                )
            )
        print(f"  {pi_mode}: {len(results)}/{len(problems)} questions", flush=True)
    return results


