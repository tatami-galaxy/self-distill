"""
Measure how each privileged context (PI) lifts the SDFT self-teacher's pass@k on
the (DeepMath) train set: full solution vs. answer vs. hint vs. no PI.

The self-teacher is the model conditioned on the query + privileged context. With
teacher_model_kind="base" the teacher IS the base student at initialization, so
this is training-free: we sample from the base model under each PI's teacher
prompt (built exactly as SDFTTrainer builds it) and grade against the gold answer.
pass@k(PI) - pass@k(none) is the informativeness of that PI; `answer` is a near-
trivial ceiling (the value is in the prompt), `hint` is the interesting middle.

Eval set = a random subset of the hint cache (train/gen_hints.py), which carries
question + final_answer + hint; `full` solutions are rejoined from DeepMath. All
arms are evaluated on the SAME problems (restricted to those whose full-PI prompt
fits the context) so every pass@k shares a denominator.

Reuses run_eval.pass_at_k / compute_pass_at_k and utils.grade.

CUDA_VISIBLE_DEVICES=0 uv run python -m eval.passk_pi \
    --model Qwen/Qwen3-1.7B --num-problems 128 --n 8 --k 1 8
"""

import argparse
import json
import os
import random
import time

from datasets import load_from_disk
from vllm import LLM, SamplingParams

from eval.run_eval import compute_pass_at_k
from train.train_sdft import PI_ANSWER, PI_FULL, PI_HINT, TEACHER_PROMPT_TEMPLATE
from utils import format_prompt_math, grade, hint_path, load_deepmath


def build_teacher_messages(problem: dict, pi_mode: str) -> list[dict]:
    """Teacher prompt for one PI mode, mirroring SDFTTrainer._compose_teacher_prompt:
    keep the system turn, fold the privileged context into the user turn via
    TEACHER_PROMPT_TEMPLATE. `none` is the plain student prompt (no PI)."""
    q = problem["question"]
    messages = format_prompt_math(q)  # [system, user(question)]
    if pi_mode == "none":
        return messages
    if pi_mode == "full":
        privileged_context = PI_FULL.format(demo=problem["solution"])
    elif pi_mode == "answer":
        privileged_context = PI_ANSWER.format(answer=problem["answer"])
    elif pi_mode == "hint":
        privileged_context = PI_HINT.format(hint=problem["hint"])
    else:
        raise ValueError(f"unknown pi_mode {pi_mode!r}")
    user_text = TEACHER_PROMPT_TEMPLATE.format(prompt=q, privileged_context=privileged_context)
    return messages[:-1] + [{"role": "user", "content": user_text}]


def load_eval_problems(model: str, num_problems: int, seed: int, need_full: bool) -> list[dict]:
    """Random subset of the hint cache, with `full` solutions rejoined from DeepMath.

    The hint cache defines the set (every problem has a hint) and carries
    question/final_answer/hint; we assert it was generated by `model` (self-purity).
    """
    path = hint_path(model)
    if not os.path.isdir(path):
        raise FileNotFoundError(
            f"No hint cache for {model} at {path}. Generate it first:\n"
            f"  python -m train.gen_hints --model {model} --max-samples <N>"
        )
    hints = load_from_disk(path)
    gen_models = set(hints.unique("gen_model"))
    if gen_models != {model}:
        raise ValueError(f"Hint cache at {path} was generated by {gen_models}, not {model!r}.")

    n = min(num_problems, len(hints))
    idx = sorted(random.Random(seed).sample(range(len(hints)), n))
    sub = hints.select(idx)

    problems = [
        {"question": r["question"], "answer": str(r["final_answer"]), "hint": r["hint"]}
        for r in sub
    ]

    if need_full:
        # Rejoin R1 solutions by question (hints came from these DeepMath rows).
        sol_by_q = {r["question"]: r["r1_solution_1"] for r in load_deepmath()}
        for p in problems:
            p["solution"] = sol_by_q.get(p["question"])
        missing = sum(p["solution"] is None for p in problems)
        if missing:
            print(f"  warning: {missing}/{len(problems)} problems had no DeepMath solution to rejoin")
    return problems


def restrict_to_full_feasible(problems, tokenizer, budget: int):
    """Keep only problems whose full-PI teacher prompt fits `budget` tokens, so
    every arm is scored on an identical problem set (full is the longest prompt)."""
    feasible = []
    for p in problems:
        if not p.get("solution"):
            continue
        ids = tokenizer.apply_chat_template(
            [build_teacher_messages(p, "full")],
            add_generation_prompt=True, tokenize=True, return_dict=True,
        )["input_ids"][0]
        if len(ids) <= budget:
            feasible.append(p)
    dropped = len(problems) - len(feasible)
    print(f"  common eval set = {len(feasible)} problems whose full-PI prompt fits "
          f"{budget} tokens (dropped {dropped})")
    return feasible


def eval_pi_mode(llm, tokenizer, problems, pi_mode, sampling_params) -> list[dict]:
    prompts = [
        tokenizer.apply_chat_template(
            build_teacher_messages(p, pi_mode), tokenize=False, add_generation_prompt=True
        )
        for p in problems
    ]
    outputs = llm.generate(prompts, sampling_params)
    results = []
    for p, out in zip(problems, outputs, strict=True):
        n_correct = sum(grade(comp.text, p["answer"])[1] for comp in out.outputs)
        results.append({"n_samples": len(out.outputs), "n_correct": n_correct})
    return results


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--model", default="Qwen/Qwen3-1.7B",
                   help="Self-teacher = this base model. Must match the hint cache's gen_model.")
    p.add_argument("--pi-modes", nargs="+", default=["none", "answer", "hint", "full"],
                   choices=["none", "answer", "hint", "full"],
                   help="PI arms to compare. 'none' is the no-PI student baseline.")
    p.add_argument("--num-problems", type=int, default=128,
                   help="Random subset of the train (hint) set to evaluate on.")
    p.add_argument("--n", type=int, default=8, help="Samples per problem (n >= max k).")
    p.add_argument("--k", type=int, nargs="+", default=[1, 8], help="pass@k values to report.")
    p.add_argument("--max-tokens", type=int, default=8192,
                   help="Completion budget. Keep generous so full reasoning isn't "
                        "truncated (truncation -> no \\boxed -> undercounts pass@k).")
    p.add_argument("--output-dir", default="results/passk_pi")
    p.add_argument("--save-samples", action="store_true",
                   help="Also dump per-problem n_correct for each mode.")
    # vLLM
    p.add_argument("--max-model-len", type=int, default=32768)
    p.add_argument("--gpu-memory-utilization", type=float, default=0.9)
    p.add_argument("--tensor-parallel-size", type=int, default=1)
    p.add_argument("--seed", type=int, default=42)
    args = p.parse_args()

    if max(args.k) > args.n:
        p.error(f"--k values must be <= --n ({args.n}); got --k {args.k}")

    problems = load_eval_problems(
        args.model, args.num_problems, args.seed, need_full=("full" in args.pi_modes)
    )
    print(f"Loaded {len(problems)} eval problems for {args.model}")

    llm = LLM(
        model=args.model,
        max_model_len=args.max_model_len,
        gpu_memory_utilization=args.gpu_memory_utilization,
        tensor_parallel_size=args.tensor_parallel_size,
        seed=args.seed,
        trust_remote_code=True,
    )
    tokenizer = llm.get_tokenizer()
    sampling_params = SamplingParams(
        n=args.n, max_tokens=args.max_tokens, seed=args.seed,
    )

    # Fix a common problem set across arms (full is the binding constraint).
    if "full" in args.pi_modes:
        budget = args.max_model_len - args.max_tokens
        problems = restrict_to_full_feasible(problems, tokenizer, budget)

    summary = {mode: {} for mode in args.pi_modes}
    per_problem = {}
    t0 = time.time()
    for mode in args.pi_modes:
        results = eval_pi_mode(llm, tokenizer, problems, mode, sampling_params)
        pak = compute_pass_at_k(results, args.k)
        summary[mode] = {f"pass@{k}": pak[k] for k in args.k}
        per_problem[mode] = [r["n_correct"] for r in results]
        print(f"  {mode:7s} " + "  ".join(f"pass@{k}={pak[k]*100:5.1f}%" for k in args.k))
    elapsed = time.time() - t0

    # Report table
    print(f"\n{'='*60}\npass@k by PI ({len(problems)} problems, n={args.n}, ")
    header = "PI mode  " + "  ".join(f"pass@{k:<3}" for k in args.k)
    print(header)
    for mode in args.pi_modes:
        row = f"{mode:7s}  " + "  ".join(f"{summary[mode][f'pass@{k}']*100:6.1f}" for k in args.k)
        print(row)

    # Save
    out = {
        "model": args.model,
        "n_problems": len(problems),
        "n_samples": args.n,
        "ks": args.k,
        "max_tokens": args.max_tokens,
        "seed": args.seed,
        "elapsed_s": elapsed,
        "pass_at_k": summary,
    }
    if args.save_samples:
        out["per_problem_n_correct"] = per_problem
    out_dir = os.path.join(args.output_dir, args.model.replace("/", "_"))
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "passk_pi_summary.json")
    with open(out_path, "w") as f:
        json.dump(out, f, indent=2)
    print(f"\nSaved -> {out_path}")


if __name__ == "__main__":
    main()
