"""Build a privileged-information (PI) training dataset for a math source dataset.

Run once per mode. Each run materializes an on-disk HF dataset with three columns,
`question`, `answer`, and `privileged_context`. The training code builds the student
prompt (system prompt + chat formatting) from `question`; `privileged_context` is
what `trl.experimental.sdft.SDFTTrainer` injects into the teacher's user turn as
`"{prompt}\n\n{privileged_context}"` before scoring the student's completion. The
output schema is identical across datasets, so the keep-set and training code are
dataset-agnostic.

Datasets (`--dataset`, see DATASETS):
  deepmath - zwhe99/DeepMath-103K. r1 solutions carry a `<think>` reasoning trace,
             so the full richness sweep is available (full / tail / alpha).
  numina   - AI-MO/NuminaMath-1.5. Concise human solutions with NO reasoning trace,
             so only answer / solution / hint exist. Filtered to checkable problems
             (math-word-problem, valid problem + solution, non-proof answer, non
             -synthetic).

Modes (`--mode`); availability is per dataset (see DatasetSpec.modes):
  full     - the entire reference solution incl. reasoning trace      (deepmath)
  alpha    - exposure sweep: the first `alpha` fraction of the reasoning
             (think) trace only -- no post-`</think>` solution, no answer
             (alpha=1 = full trace); tokenized with --tokenizer            (deepmath)
  tail     - only the polished solution after `</think>` (reasoning stripped;
             the complement of `alpha`). Contains the answer.             (deepmath)
  solution - the whole reference solution (numina has no trace to split)   (numina)
  answer   - only the final answer                                         (both)
  hint     - 1-3 line strategy hint generated by `--hint-model` (vLLM, inline);
             the hint model sees the solution, not the reasoning trace     (both)

`full`, `answer`, `tail`, `solution`, `alpha` are pure deterministic transforms.

Output layout (under `--output-root`, default `data/pi_<dataset>`):
  <mode> -> data/pi_<dataset>/<mode>      (alpha -> alpha_0.25, alpha_0.5, ...)
  hint   -> data/pi_<dataset>/hint_<model>_<think>   (raw hints cached under
            data/pi_<dataset>/hints/)

Examples
--------
python -m hint_gen.build_pi_datasets --dataset deepmath --mode full
python -m hint_gen.build_pi_datasets --dataset deepmath --mode alpha --alphas 0.25 0.5 0.75
python -m hint_gen.build_pi_datasets --dataset numina --mode answer
python -m hint_gen.build_pi_datasets --dataset numina --mode solution
python -m hint_gen.build_pi_datasets --dataset numina --mode hint --hint-model Qwen/Qwen3-4B --enable-thinking
"""

import argparse
import json
import os
from dataclasses import dataclass
from typing import Callable

from datasets import Dataset, load_dataset
from eval.utils import extract_boxed_answer  # noqa: E402


HINT_INSTRUCTION = (
    "You are helping create a hint for a math problem. "
    "Below is the problem and a full worked solution. "
    "Mention the key ideas or knowledge needed to solve the problem. "
    "Be very brief. Do NOT carry out the calculations needed and "
    "do NOT reveal the final answer. Output only the hint."
)


# ---------------------------------------------------------------------------
# Dataset adapters: map each source dataset's schema to a common interface so
# every downstream consumer sees {question, answer, privileged_context}.
# ---------------------------------------------------------------------------

@dataclass
class DatasetSpec:
    hf_id: str
    question_col: str           # source column holding the problem statement
    solution_col: str           # source column holding the reference solution
    modes: tuple[str, ...]      # PI modes valid for this dataset
    keep_row: Callable[[dict], bool]   # row-level filter applied before subsetting
    answer_fn: Callable[[dict], str]   # gold final answer for a row


def _deepmath_answer(row: dict) -> str:
    """Gold answer: prefer the dataset column, fall back to boxed in the solution."""
    ans = row.get("final_answer")
    if ans is not None and str(ans).strip():
        return str(ans).strip()
    return (extract_boxed_answer(row["r1_solution_1"]) or "").strip()


def _deepmath_keep(row: dict) -> bool:
    s = row.get("r1_solution_1")
    return s is not None and len(s.strip()) > 0


def _numina_answer(row: dict) -> str:
    return str(row.get("answer", "")).strip()


def _numina_keep(row: dict) -> bool:
    """Keep only cleanly gradable word problems: a checkable (non-proof) answer,
    a valid problem and solution, and not synthetic."""
    return (
        row.get("question_type") == "math-word-problem"
        and str(row.get("answer", "")).strip().lower() not in ("", "proof")
        and row.get("problem_is_valid") == "Yes"
        and row.get("solution_is_valid") == "Yes"
        and bool(str(row.get("solution", "")).strip())
        and not row.get("synthetic", False)
    )


DATASETS: dict[str, DatasetSpec] = {
    "deepmath": DatasetSpec(
        hf_id="zwhe99/DeepMath-103K",
        question_col="question",
        solution_col="r1_solution_1",
        modes=("full", "answer", "tail", "hint", "alpha"),
        keep_row=_deepmath_keep,
        answer_fn=_deepmath_answer,
    ),
    "numina": DatasetSpec(
        hf_id="AI-MO/NuminaMath-1.5",
        question_col="problem",
        solution_col="solution",
        modes=("answer", "solution", "hint"),
        keep_row=_numina_keep,
        answer_fn=_numina_answer,
    ),
}


def solution_text(row: dict, spec: DatasetSpec) -> str:
    return (row[spec.solution_col] or "").strip()


# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

def model_slug(model: str) -> str:
    """Filesystem-safe short name for a model id, e.g. Qwen/Qwen3-4B -> Qwen3-4B."""
    return model.rstrip("/").split("/")[-1]


def think_tag(enable_thinking: bool) -> str:
    """Tag recording how hints were produced, so thinking vs non-thinking hints
    land in separate caches/output dirs instead of overwriting each other."""
    return "think" if enable_thinking else "nothink"


def split_demo(solution: str, think_close: str) -> tuple[str, str]:
    """Split a solution into (reasoning, tail).

    `reasoning` is everything before `think_close`; `tail` is the polished
    solution that follows (and contains the answer). If the marker is absent
    (e.g. NuminaMath, which has no reasoning trace), the whole solution is
    treated as reasoning and `tail` is empty.
    """
    if think_close in solution:
        pre, post = solution.split(think_close, 1)
        return pre.strip(), post.strip()
    return solution.strip(), ""


def extract_hint(text: str, think_close: str) -> str:
    """Pull the hint out of a thinking-mode generation.

    With `enable_thinking=True` the output is `<think> reasoning </think> hint`.
    Return the content after the (last) `think_close`. If the marker is absent
    (e.g. thinking got truncated by max_tokens), fall back to the raw text so the
    failure is visible downstream rather than silently empty.
    """
    if think_close in text:
        return text.rsplit(think_close, 1)[1].strip()
    return text.strip()


def truncate_reasoning_tokens(reasoning: str, alpha: float, tokenizer) -> str:
    """Keep the first `alpha` fraction of the reasoning, measured in tokens."""
    if alpha >= 1.0:
        return reasoning
    if alpha <= 0.0:
        return ""
    ids = tokenizer.encode(reasoning, add_special_tokens=False)
    keep = max(1, int(round(len(ids) * alpha)))
    return tokenizer.decode(ids[:keep], skip_special_tokens=True).strip()


# ---------------------------------------------------------------------------
# Privileged-context construction (one per PI mode)
# ---------------------------------------------------------------------------

def pi_full(row: dict, spec: DatasetSpec) -> str:
    return (
        "A complete reference solution is provided below :\n\n"
        f"{solution_text(row, spec)}"
    )


def pi_answer(row: dict, spec: DatasetSpec) -> str:
    return f"For reference, the correct final answer is: \\boxed{{{spec.answer_fn(row)}}}."


def pi_solution(row: dict, spec: DatasetSpec) -> str:
    """The whole reference solution (datasets without a `<think>` trace)."""
    return f"A reference solution is provided below:\n\n{solution_text(row, spec)}"


def pi_hint(hint: str) -> str:
    return f"Hint: {hint.strip()}"


def pi_tail(row: dict, spec: DatasetSpec, think_close: str) -> str:
    """Expose only the polished solution after `</think>` (reasoning stripped).

    The complement of `alpha`: the clean write-up (which contains the answer)
    without the exploratory reasoning trace that precedes it. If the marker is
    absent there is no tail to expose, so return "".
    """
    _, tail = split_demo(solution_text(row, spec), think_close)
    if not tail:
        return ""
    return f"A reference solution is provided below:\n\n{tail}"


def pi_alpha(row: dict, spec: DatasetSpec, alpha: float, tokenizer, think_close: str) -> str:
    """Expose only the first `alpha` fraction of the reasoning (think) trace.

    The polished solution after `</think>` and the final answer are NOT exposed,
    so alpha=1 gives the full reasoning trace alone.
    """
    reasoning, _ = split_demo(solution_text(row, spec), think_close)
    partial = truncate_reasoning_tokens(reasoning, alpha, tokenizer)
    if not partial:
        return ""
    if alpha >= 1.0:
        return f"A reference reasoning trace is provided below:\n\n{partial}"
    return (
        "The beginning of a reference reasoning trace is provided below:\n\n"
        f"{partial}\n\n[...]"
    )


# ---------------------------------------------------------------------------
# Data loading + saving
# ---------------------------------------------------------------------------

def load_subset(spec: DatasetSpec, dataset_id: str, max_samples: int | None,
                seed: int, num_proc: int) -> Dataset:
    """Load the train split, apply the dataset's keep filter, shuffle, subset."""
    ds = load_dataset(dataset_id, split="train")
    n0 = len(ds)
    ds = ds.filter(spec.keep_row, num_proc=num_proc)
    print(f"  kept {len(ds)}/{n0} rows after dataset filter")
    ds = ds.shuffle(seed=seed)
    if max_samples:
        ds = ds.select(range(min(max_samples, len(ds))))
    return ds


def save_variant(ds: Dataset, spec: DatasetSpec, name: str, build_pc, output_root: str, num_proc: int):
    """Map rows to {question, answer, privileged_context} via `build_pc(row)` and save.

    `answer` is the gold final answer, carried across all modes so the data is
    usable for reward grading (and self-distillation). The system prompt / chat
    formatting is intentionally NOT applied here; the training code owns it.
    """
    out = ds.map(
        lambda row: {
            "question": row[spec.question_col],
            "answer": spec.answer_fn(row),
            "privileged_context": build_pc(row),
        },
        remove_columns=ds.column_names,
        num_proc=num_proc,
    )
    path = os.path.join(output_root, name)
    out.save_to_disk(path)
    print(f"  [{name}] {len(out)} rows -> {path}")
    print(f"    sample PI: {out[0]['privileged_context'][:160]!r}")


# ---------------------------------------------------------------------------
# Hint generation
# ---------------------------------------------------------------------------

def hint_gen_prompt(question: str, solution: str, instruction: str, think_close: str) -> list[dict]:
    _, tail = split_demo(solution, think_close)
    body = tail if tail else solution  # polished tail is concise; fall back to full
    return [
        {"role": "system", "content": instruction},
        {"role": "user", "content": f"Problem:\n{question}\n\nSolution:\n{body}"},
    ]


def generate_hints(ds: Dataset, spec: DatasetSpec, args) -> list[str]:
    """Generate one strategy hint per row with vLLM. Cached to disk (keyed by
    model) so reruns and the dataset build don't regenerate."""
    slug = model_slug(args.hint_model)
    cache = os.path.join(
        args.output_root, "hints",
        f"hints_{slug}_{think_tag(args.enable_thinking)}_n{args.max_samples or 'all'}_s{args.seed}.json",
    )
    if os.path.exists(cache):
        with open(cache) as f:
            hints = json.load(f)
        if len(hints) == len(ds):
            print(f"  reusing cached hints -> {cache}")
            return hints
        print(f"  cached hints stale ({len(hints)} != {len(ds)}); regenerating")

    from vllm import LLM, SamplingParams
    from transformers import AutoTokenizer

    print(f"  generating hints for {len(ds)} rows with {args.hint_model}")
    tok = AutoTokenizer.from_pretrained(args.hint_model, trust_remote_code=True)
    prompts = [
        tok.apply_chat_template(
            hint_gen_prompt(row[spec.question_col], solution_text(row, spec),
                            args.hint_instruction, args.think_close),
            tokenize=False, add_generation_prompt=True, enable_thinking=args.enable_thinking,
        )
        for row in ds
    ]
    llm = LLM(model=args.hint_model, tensor_parallel_size=args.tensor_parallel_size, trust_remote_code=True)
    sp = SamplingParams(max_tokens=args.max_tokens)
    outputs = llm.generate(prompts, sp)
    hints = [extract_hint(o.outputs[0].text, args.think_close) for o in outputs]

    for h in hints:
        print(h)
        print('\n')
    quit()
    
    n_empty = sum(1 for h in hints if not h)
    if n_empty:
        print(f"  WARNING: {n_empty}/{len(hints)} hints empty (thinking likely truncated; raise --max-tokens)")

    os.makedirs(os.path.dirname(cache), exist_ok=True)
    with open(cache, "w") as f:
        json.dump(hints, f)
    print(f"  wrote {len(hints)} hints -> {cache}")
    return hints


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--dataset", default="deepmath", choices=list(DATASETS),
                   help="Source dataset (selects schema + valid modes)")
    p.add_argument("--dataset-id", default=None,
                   help="Override the HF dataset id (default: the spec's hf_id)")
    p.add_argument("--mode", required=True,
                   choices=["full", "answer", "tail", "solution", "hint", "alpha"],
                   help="Which PI to build (run one at a time)")
    p.add_argument("--output-root", default=None,
                   help="Default: data/pi_<dataset>")
    p.add_argument("--max-samples", type=int, default=10000,
                   help="Train subset size. Pass a large value for the full run.")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--num-proc", type=int, default=4)
    p.add_argument("--think-close", default="</think>",
                   help="Marker separating the reasoning trace from the polished solution")
    # alpha mode
    p.add_argument("--alphas", nargs="+", type=float, default=[0.25, 0.5, 0.75],
                   help="Exposure fractions for --mode alpha (one dataset each)")
    p.add_argument("--tokenizer", default="Qwen/Qwen3-4B",
                   help="Tokenizer for alpha token-fraction truncation")
    # hint mode
    p.add_argument("--hint-model", default=None,
                   help="Model that generates hints (required for --mode hint); "
                        "its name is encoded in the output dir")
    p.add_argument("--hint-instruction", default=HINT_INSTRUCTION)
    p.add_argument("--tensor-parallel-size", type=int, default=1)
    p.add_argument("--enable-thinking", action=argparse.BooleanOptionalAction, default=False,
                   help="Toggle the hint model's thinking mode (default off; pass "
                        "--enable-thinking to turn it on). When on, the hint is extracted "
                        "after the think trace.")
    p.add_argument("--max-tokens", type=int, default=32000,
                   help="Generation budget for hints. With thinking enabled it must fit the "
                        "think trace + the hint; too small truncates the hint away.")
    args = p.parse_args()

    spec = DATASETS[args.dataset]
    if args.mode not in spec.modes:
        p.error(f"--mode {args.mode} is not available for dataset '{args.dataset}' "
                f"(valid: {', '.join(spec.modes)})")
    if args.mode == "hint" and not args.hint_model:
        p.error("--mode hint requires --hint-model")
    if args.output_root is None:
        args.output_root = f"data/pi_{args.dataset}"
    dataset_id = args.dataset_id or spec.hf_id

    ds = load_subset(spec, dataset_id, args.max_samples, args.seed, args.num_proc)
    print(f"Loaded {len(ds)} rows from {dataset_id} (dataset={args.dataset}, mode={args.mode})")

    if args.mode == "full":
        save_variant(ds, spec, "full", lambda row: pi_full(row, spec), args.output_root, args.num_proc)
    elif args.mode == "answer":
        save_variant(ds, spec, "answer", lambda row: pi_answer(row, spec), args.output_root, args.num_proc)
    elif args.mode == "solution":
        save_variant(ds, spec, "solution", lambda row: pi_solution(row, spec), args.output_root, args.num_proc)
    elif args.mode == "tail":
        save_variant(ds, spec, "tail",
                     lambda row: pi_tail(row, spec, args.think_close),
                     args.output_root, args.num_proc)
    elif args.mode == "alpha":
        from transformers import AutoTokenizer
        tok = AutoTokenizer.from_pretrained(args.tokenizer, trust_remote_code=True)
        for a in args.alphas:
            save_variant(ds, spec, f"alpha_{a:g}",
                         lambda row, a=a: pi_alpha(row, spec, a, tok, args.think_close),
                         args.output_root, args.num_proc)
    elif args.mode == "hint":
        hints = generate_hints(ds, spec, args)
        ds_h = ds.add_column("_hint", hints)
        save_variant(ds_h, spec, f"hint_{model_slug(args.hint_model)}_{think_tag(args.enable_thinking)}",
                     lambda row: pi_hint(row["_hint"]),
                     args.output_root, args.num_proc)


if __name__ == "__main__":
    main()
