"""Build a privileged-information (PI) training dataset from DeepMath-103K.

Run once per mode. Each run materializes an on-disk HF dataset with two columns,
`question` and `privileged_context`. The training code builds the student prompt
(system prompt + chat formatting) from `question`; `privileged_context` is what
`trl.experimental.sdft.SDFTTrainer` injects into the teacher's user turn as
`"{prompt}\n\n{privileged_context}"` before scoring the student's completion.

Modes (`--mode`):
  full    - the entire r1_solution_1 demonstration
  answer  - only the final boxed answer
  hint    - 1-3 line strategy hint generated by `--hint-model` (vLLM, inline)
  alpha   - exposure sweep: for each `--alphas` value, the first `alpha`
            fraction of the reasoning (think) trace only -- no post-`</think>`
            solution and no final answer (alpha=1 = full trace) 
            (tokenized with Qwen3-4B)

`full`, `answer`, `alpha` are pure deterministic transforms (no model).

Output layout (under `--output-root`, default `data/pi`):
  full -> data/pi/full        answer -> data/pi/answer
  alpha -> data/pi/alpha_0.25, data/pi/alpha_0.5, ...   (one dir per alpha)
  hint -> data/pi/hint_<model>   (the hint model is encoded in the name; raw
          hints cached at data/pi/hints/hints_<model>_n<N>_s<seed>.json)

Examples
--------
python -m hint_gen.build_pi_datasets --mode full
python -m hint_gen.build_pi_datasets --mode answer
python -m hint_gen.build_pi_datasets --mode alpha --alphas 0.25 0.5 0.75
python -m hint_gen.build_pi_datasets --mode hint --hint-model Qwen/Qwen3-4B    --tensor-parallel-size 1 --enable-thinking
python -m hint_gen.build_pi_datasets --mode hint --hint-model Qwen/Qwen3.6-27B --tensor-parallel-size 2 --enable-thinking
"""

import argparse
import json
import os
from datasets import Dataset, load_dataset
from eval.utils import extract_boxed_answer  # noqa: E402


HINT_INSTRUCTION = (
    "You are helping create a hint for a math problem. "
    "Below is the problem and a full worked solution. "
    "Mention the key ideas or knowledge needed to solve the problem. "
    "Be very brief. Do NOT carry out the calculations needed and "
    "do NOT reveal the final answer. Output only the hint."
)

# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

def model_slug(model: str) -> str:
    """Filesystem-safe short name for a model id, e.g. Qwen/Qwen3-4B -> Qwen3-4B."""
    return model.rstrip("/").split("/")[-1]


def think_tag(enable_thinking: bool) -> str:
    """Tag recording how hints were produced, so thinking vs non-thinking hints
    land in separate caches/output dirs instead of overwriting each other."""
    return "think" if enable_thinking else "nothink"


def split_demo(solution: str, think_close: str) -> tuple[str, str]:
    """Split an r1 solution into (reasoning, tail).

    `reasoning` is everything before `think_close`; `tail` is the polished
    solution that follows (and contains the boxed answer). If the marker is
    absent, the whole solution is treated as reasoning.
    """
    if think_close in solution:
        pre, post = solution.split(think_close, 1)
        return pre.strip(), post.strip()
    return solution.strip(), ""


def extract_hint(text: str, think_close: str) -> str:
    """Pull the hint out of a thinking-mode generation.

    With `enable_thinking=True` the output is `<think> reasoning </think> hint`.
    Return the content after the (last) `think_close`. If the marker is absent
    (e.g. thinking got truncated by max_tokens), fall back to the raw text so the
    failure is visible downstream rather than silently empty.
    """
    if think_close in text:
        return text.rsplit(think_close, 1)[1].strip()
    return text.strip()


def final_answer(row: dict) -> str:
    """Gold final answer: prefer the dataset column, fall back to boxed."""
    ans = row.get("final_answer")
    if ans is not None and str(ans).strip():
        return str(ans).strip()
    return (extract_boxed_answer(row["r1_solution_1"]) or "").strip()


def truncate_reasoning_tokens(reasoning: str, alpha: float, tokenizer) -> str:
    """Keep the first `alpha` fraction of the reasoning, measured in tokens."""
    if alpha >= 1.0:
        return reasoning
    if alpha <= 0.0:
        return ""
    ids = tokenizer.encode(reasoning, add_special_tokens=False)
    keep = max(1, int(round(len(ids) * alpha)))
    return tokenizer.decode(ids[:keep], skip_special_tokens=True).strip()


# ---------------------------------------------------------------------------
# Privileged-context construction (one per PI mode)
# ---------------------------------------------------------------------------

def pi_full(row: dict) -> str:
    return (
        "A complete reference solution is provided below :\n\n"
        f"{row['r1_solution_1'].strip()}"
    )


def pi_answer(row: dict) -> str:
    return f"For reference, the correct final answer is: \\boxed{{{final_answer(row)}}}."


def pi_hint(hint: str) -> str:
    return f"Hint: {hint.strip()}"


def pi_alpha(row: dict, alpha: float, tokenizer, think_close: str) -> str:
    """Expose only the first `alpha` fraction of the reasoning (think) trace.

    The polished solution after `</think>` and the final answer are NOT exposed,
    so alpha=1 gives the full reasoning trace alone.
    """
    reasoning, _ = split_demo(row["r1_solution_1"], think_close)
    partial = truncate_reasoning_tokens(reasoning, alpha, tokenizer)
    if not partial:
        return ""
    if alpha >= 1.0:
        return f"A reference reasoning trace is provided below:\n\n{partial}"
    return (
        "The beginning of a reference reasoning trace is provided below:\n\n"
        f"{partial}\n\n[...]"
    )


# ---------------------------------------------------------------------------
# Data loading + saving
# ---------------------------------------------------------------------------

def load_subset(dataset: str, max_samples: int | None, seed: int) -> Dataset:
    """Load DeepMath train, drop empty r1_solution_1, shuffle, subset."""
    ds = load_dataset(dataset, split="train")
    ds = ds.filter(
        lambda x: x["r1_solution_1"] is not None and len(x["r1_solution_1"].strip()) > 0,
        num_proc=4,
    )
    ds = ds.shuffle(seed=seed)
    if max_samples:
        ds = ds.select(range(min(max_samples, len(ds))))
    return ds


def save_variant(ds: Dataset, name: str, build_pc, output_root: str, num_proc: int):
    """Map rows to {question, answer, privileged_context} via `build_pc(row)` and save.

    `answer` is the gold final answer, carried across all modes so the data is
    usable for RL reward grading (and self-distillation). The system prompt /
    chat formatting is intentionally NOT applied here; the training code owns it.
    """
    out = ds.map(
        lambda row: {
            "question": row["question"],
            "answer": final_answer(row),
            "privileged_context": build_pc(row),
        },
        remove_columns=ds.column_names,
        num_proc=num_proc,
    )
    path = os.path.join(output_root, name)
    out.save_to_disk(path)
    print(f"  [{name}] {len(out)} rows -> {path}")
    print(f"    sample PI: {out[0]['privileged_context'][:160]!r}")


# ---------------------------------------------------------------------------
# Hint generation
# ---------------------------------------------------------------------------

def hint_gen_prompt(question: str, solution: str, instruction: str, think_close: str) -> list[dict]:
    _, tail = split_demo(solution, think_close)
    body = tail if tail else solution  # polished tail is concise; fall back to full
    return [
        {"role": "system", "content": instruction},
        {"role": "user", "content": f"Problem:\n{question}\n\nSolution:\n{body}"},
    ]


def generate_hints(ds: Dataset, args) -> list[str]:
    """Generate one strategy hint per row with vLLM. Cached to disk (keyed by
    model) so reruns and the dataset build don't regenerate."""
    slug = model_slug(args.hint_model)
    cache = os.path.join(
        args.output_root, "hints",
        f"hints_{slug}_{think_tag(args.enable_thinking)}_n{args.max_samples or 'all'}_s{args.seed}.json",
    )
    if os.path.exists(cache):
        with open(cache) as f:
            hints = json.load(f)
        if len(hints) == len(ds):
            print(f"  reusing cached hints -> {cache}")
            return hints
        print(f"  cached hints stale ({len(hints)} != {len(ds)}); regenerating")

    from vllm import LLM, SamplingParams
    from transformers import AutoTokenizer

    print(f"  generating hints for {len(ds)} rows with {args.hint_model}")
    tok = AutoTokenizer.from_pretrained(args.hint_model, trust_remote_code=True)
    prompts = [
        tok.apply_chat_template(
            hint_gen_prompt(row["question"], row["r1_solution_1"], args.hint_instruction, args.think_close),
            tokenize=False, add_generation_prompt=True, enable_thinking=args.enable_thinking,
        )
        for row in ds
    ]
    llm = LLM(model=args.hint_model, tensor_parallel_size=args.tensor_parallel_size, trust_remote_code=True)
    sp = SamplingParams(max_tokens=args.max_tokens)
    outputs = llm.generate(prompts, sp)
    hints = [extract_hint(o.outputs[0].text, args.think_close) for o in outputs]
    n_empty = sum(1 for h in hints if not h)
    if n_empty:
        print(f"  WARNING: {n_empty}/{len(hints)} hints empty (thinking likely truncated; raise --max-tokens)")

    os.makedirs(os.path.dirname(cache), exist_ok=True)
    with open(cache, "w") as f:
        json.dump(hints, f)
    print(f"  wrote {len(hints)} hints -> {cache}")
    return hints


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--mode", required=True, choices=["full", "answer", "hint", "alpha"],
                   help="Which PI to build (run one at a time)")
    p.add_argument("--dataset", default="zwhe99/DeepMath-103K")
    p.add_argument("--output-root", default="data/pi")
    p.add_argument("--max-samples", type=int, default=10000,
                   help="Train subset size. Pass a large value for the full run.")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--num-proc", type=int, default=4)
    p.add_argument("--think-close", default="</think>",
                   help="Marker separating the reasoning trace from the polished solution")
    # alpha mode
    p.add_argument("--alphas", nargs="+", type=float, default=[0.25, 0.5, 0.75],
                   help="Exposure fractions for --mode alpha (one dataset each)")
    p.add_argument("--tokenizer", default="Qwen/Qwen3-4B",
                   help="Tokenizer for alpha token-fraction truncation")
    # hint mode
    p.add_argument("--hint-model", default=None,
                   help="Model that generates hints (required for --mode hint); "
                        "its name is encoded in the output dir")
    p.add_argument("--hint-instruction", default=HINT_INSTRUCTION)
    p.add_argument("--tensor-parallel-size", type=int, default=1)
    p.add_argument("--enable-thinking", action=argparse.BooleanOptionalAction, default=False,
                   help="Toggle the hint model's thinking mode (default off; pass "
                        "--enable-thinking to turn it on). When on, the hint is extracted "
                        "after the think trace.")
    p.add_argument("--max-tokens", type=int, default=32000,
                   help="Generation budget for hints. With thinking enabled it must fit the "
                        "think trace + the hint; too small truncates the hint away.")
    args = p.parse_args()

    if args.mode == "hint" and not args.hint_model:
        p.error("--mode hint requires --hint-model")

    ds = load_subset(args.dataset, args.max_samples, args.seed)
    print(f"Loaded {len(ds)} rows from {args.dataset} (mode={args.mode})")

    if args.mode == "full":
        save_variant(ds, "full", pi_full, args.output_root, args.num_proc)
    elif args.mode == "answer":
        save_variant(ds, "answer", pi_answer, args.output_root, args.num_proc)
    elif args.mode == "alpha":
        from transformers import AutoTokenizer
        tok = AutoTokenizer.from_pretrained(args.tokenizer, trust_remote_code=True)
        for a in args.alphas:
            save_variant(ds, f"alpha_{a:g}",
                         lambda row, a=a: pi_alpha(row, a, tok, args.think_close),
                         args.output_root, args.num_proc)
    elif args.mode == "hint":
        hints = generate_hints(ds, args)
        ds_h = ds.add_column("_hint", hints)
        save_variant(ds_h, f"hint_{model_slug(args.hint_model)}_{think_tag(args.enable_thinking)}",
                     lambda row: pi_hint(row["_hint"]),
                     args.output_root, args.num_proc)


if __name__ == "__main__":
    main()
